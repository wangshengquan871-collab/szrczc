'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const bcrypt = require('bcrypt');
const { backendFixture } = require('./helpers/auth-backend-fixture');
const registration = { username: '用户甲', email: 'new-user@example.invalid', password: 'TestPassword123', confirmPassword: 'TestPassword123' };

test('正式后端流程：注册、重复、错误密码、正确登录、me与退出（SQL替身，真实bcrypt/MySQL Session适配器）', async t => {
  const fixture = await backendFixture(t);
  assert.equal((await fixture.request('/api/auth/me')).status, 401);
  await fixture.csrf();
  const anonymousCookie = fixture.cookie;
  const register = await fixture.request('/api/auth/register', { method: 'POST', body: { ...registration, role: 'admin' } });
  assert.equal(register.status, 201);
  assert.equal((await register.json()).redirect, '/login');
  assert.equal((await fixture.request('/api/auth/me')).status, 401);
  const user = fixture.pool.records[0];
  assert.equal(user.role, 'user');
  assert.notEqual(user.password_hash, registration.password);
  assert.ok(await bcrypt.compare(registration.password, user.password_hash));
  const duplicate = await fixture.request('/api/auth/register', { method: 'POST', body: registration });
  assert.equal(duplicate.status, 409);
  const fields = (await duplicate.json()).fields;
  assert.ok(fields.username && fields.email);
  const onlyUsername = await fixture.request('/api/auth/register', { method: 'POST', body: { ...registration, email: 'another@example.invalid' } });
  assert.deepEqual(Object.keys((await onlyUsername.json()).fields), ['username']);
  const wrong = await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: 'WrongPassword123' } });
  assert.equal(wrong.status, 401);
  assert.equal((await wrong.json()).code, 'INVALID_CREDENTIALS');
  const login = await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: registration.password, returnTo: '//evil.example' } });
  assert.equal(login.status, 200);
  assert.equal((await login.json()).redirect, '/index.html');
  assert.notEqual(fixture.cookie, anonymousCookie);
  assert.match(login.headers.getSetCookie().join(';'), /HttpOnly/);
  assert.match(login.headers.getSetCookie().join(';'), /SameSite=Lax/);
  assert.ok(user.last_login_at instanceof Date);
  assert.ok([...fixture.pool.sessions.values()].some(row => row.user_id === user.id));
  assert.equal((await fixture.request('/api/auth/me', { cookie: anonymousCookie })).status, 401);
  const me = await fixture.request('/api/auth/me');
  assert.equal(me.status, 200);
  const profile = (await me.json()).user;
  assert.equal(profile.username, registration.username);
  assert.equal(profile.createdAt, user.created_at.toISOString());
  assert.ok(profile.lastLoginAt);
  assert.ok(!('password_hash' in profile));
  assert.equal(me.headers.get('cache-control'), 'no-store');
  assert.equal(me.headers.get('pragma'), 'no-cache');
  assert.equal(me.headers.get('expires'), '0');
  assert.equal((await fixture.request('/account')).status, 200);
  assert.equal((await fixture.request('/index.html')).status, 200);
  await fixture.csrf();
  const oldCookie = fixture.cookie;
  const logout = await fixture.request('/api/auth/logout', { method: 'POST' });
  assert.equal(logout.status, 200);
  assert.equal(logout.headers.get('cache-control'), 'no-store');
  assert.equal(logout.headers.get('pragma'), 'no-cache');
  assert.equal(logout.headers.get('expires'), '0');
  assert.equal(fixture.pool.sessions.size, 0);
  assert.equal((await fixture.request('/api/auth/me', { cookie: oldCookie })).status, 401);
  const account = await fixture.request('/account');
  assert.equal(account.status, 302);
  assert.match(account.headers.get('location'), /^\/login/);
  await fixture.csrf();
  assert.equal((await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.email.toUpperCase(), password: registration.password } })).status, 200);
  assert.ok(fixture.pool.audit.some(row => row[2] === 0));
  assert.ok(fixture.pool.audit.some(row => row[2] === 1));
  for (const { sql } of fixture.pool.calls.filter(call => !call.sql.includes('??'))) assert.ok(!sql.includes(registration.email));
});

test('正式API拒绝缺失/错误CSRF、外部Origin及无效参数', async t => {
  const fixture = await backendFixture(t);
  const missing = await fixture.request('/api/auth/login', { method: 'POST', body: {}, useCsrf: false });
  assert.equal(missing.status, 403);
  await fixture.csrf();
  assert.equal((await fixture.request('/api/auth/register', { method: 'POST', body: registration, headers: { Origin: 'https://evil.example' } })).status, 403);
  const invalid = await fixture.request('/api/auth/register', { method: 'POST', body: { ...registration, username: 'ab', email: 'bad', password: 'short', confirmPassword: 'different' } });
  assert.equal(invalid.status, 422);
  assert.equal(Object.keys((await invalid.json()).fields).length, 4);
  assert.equal(fixture.pool.records.length, 0);
});

test('会话保存或用户关联失败不返回登录成功，禁用账号后会话立即失效', async t => {
  const fixture = await backendFixture(t);
  await fixture.csrf();
  await fixture.request('/api/auth/register', { method: 'POST', body: registration });
  fixture.pool.state.failSessionWrite = true;
  const failed = await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: registration.password } });
  assert.equal(failed.status, 503);
  assert.equal(fixture.pool.sessions.size, 0);
  assert.equal(fixture.pool.records[0].last_login_at, null);
  fixture.pool.state.failSessionWrite = false;
  await fixture.csrf();
  fixture.pool.state.failSessionLink = true;
  assert.equal((await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: registration.password } })).status, 500);
  assert.equal(fixture.pool.sessions.size, 0);
  assert.equal(fixture.pool.records[0].last_login_at, null);
  fixture.pool.state.failSessionLink = false;
  await fixture.csrf();
  assert.equal((await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: registration.password } })).status, 200);
  fixture.pool.records[0].status = 'disabled';
  assert.equal((await fixture.request('/api/auth/me')).status, 401);
  assert.equal(fixture.pool.sessions.size, 0);
});

test('正式登录接口第11次请求触发限流，绝对会话过期被拒绝', async t => {
  const fixture = await backendFixture(t);
  await fixture.csrf();
  await fixture.request('/api/auth/register', { method: 'POST', body: registration });
  assert.equal((await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: registration.password } })).status, 200);
  const row = [...fixture.pool.sessions.values()].find(row => row.user_id);
  const saved = JSON.parse(row.data); saved.authExpiresAt = Date.now() - 1; row.data = JSON.stringify(saved);
  assert.equal((await fixture.request('/api/auth/me')).status, 401);
  await fixture.csrf();
  for (let i = 0; i < 9; i++) assert.equal((await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: 'WrongPassword123' } })).status, 401);
  const limited = await fixture.request('/api/auth/login', { method: 'POST', body: { identifier: registration.username, password: registration.password } });
  assert.equal(limited.status, 429);
  assert.ok(limited.headers.get('retry-after'));
});

test('生产代理配置生成Secure、HttpOnly、SameSite和__Host Cookie', async t => {
  const fixture = await backendFixture(t, { production: true });
  const csrf = await fixture.request('/api/auth/csrf');
  const cookie = csrf.headers.getSetCookie().join(';');
  assert.match(cookie, /__Host-szp.sid=/);
  assert.match(cookie, /Secure/);
  assert.match(cookie, /HttpOnly/);
  assert.match(cookie, /SameSite=Lax/);
  assert.match(cookie, /Path=\//);
  assert.doesNotMatch(cookie, /Domain=/);
});
